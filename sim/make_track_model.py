import os
import sys
import numpy as np
import cv2

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "sync_work"))
from track_render import dist_to_axis, R_IN, R_OUT, LANE_W, N_LANES

X0, X1, Y0, Y1 = -110.0, 110.0, -60.0, 60.0
TEX_ROWS, TEX_COLS = 4096, 2048
TRACK_RGB = (196, 72, 58)
FIELD_RGB = (70, 128, 58)
OUTER_RGB = (92, 120, 70)
LINE_RGB = (235, 235, 235)


def main():
    xs = X1 - (np.arange(TEX_ROWS) + 0.5) * (X1 - X0) / TEX_ROWS
    ys = Y1 - (np.arange(TEX_COLS) + 0.5) * (Y1 - Y0) / TEX_COLS
    Y, X = np.meshgrid(ys, xs)
    mpp_x = (X1 - X0) / TEX_ROWS
    d = dist_to_axis(X, Y)
    img = np.zeros((TEX_ROWS, TEX_COLS, 3), np.uint8)
    img[:] = OUTER_RGB
    inner = d < R_IN
    stripe = ((np.floor((X + 200) / 5.0)).astype(int) % 2 == 0)
    img[inner] = FIELD_RGB
    img[inner & stripe] = (np.array(FIELD_RGB) * 0.88).astype(np.uint8)
    track = (d >= R_IN) & (d <= R_OUT)
    img[track] = TRACK_RGB
    for k in range(N_LANES + 1):
        line = np.abs(d - (R_IN + k * LANE_W)) < 0.05
        img[line] = LINE_RGB
    def square(cx, cy, rgb, s=6.0):
        m = (np.abs(X - cx) < s) & (np.abs(Y - cy) < s)
        img[m] = rgb
    square(100, 50, (40, 60, 220))
    square(100, -50, (230, 210, 40))

    mdir = os.path.join(HERE, "models", "running_track")
    os.makedirs(os.path.join(mdir, "materials", "textures"), exist_ok=True)
    os.makedirs(os.path.join(mdir, "materials", "scripts"), exist_ok=True)
    cv2.imwrite(os.path.join(mdir, "materials", "textures", "track.png"), img[:, :, ::-1])
    open(os.path.join(mdir, "materials", "scripts", "track.material"), "w").write(
        """material RunningTrack/Ground
{
  technique
  {
    pass
    {
      ambient 0.9 0.9 0.9 1
      diffuse 0.9 0.9 0.9 1
      texture_unit
      {
        texture track.png
        filtering anisotropic
        max_anisotropy 8
      }
    }
  }
}
""")
    open(os.path.join(mdir, "model.config"), "w").write(
        """<?xml version="1.0"?>
<model><name>running_track</name><version>1.0</version><sdf version="1.6">model.sdf</sdf>
<description>IAAF 400m track, texture generated by make_track_model.py</description></model>
""")
    open(os.path.join(mdir, "model.sdf"), "w").write(
        f"""<?xml version="1.0"?>
<sdf version="1.6">
  <model name="running_track">
    <static>true</static>
    <link name="l">
      <visual name="ground">
        <pose>0 0 -0.005 0 0 0</pose>
        <geometry><box><size>{X1 - X0} {Y1 - Y0} 0.01</size></box></geometry>
        <material><script>
          <uri>model://running_track/materials/scripts</uri>
          <uri>model://running_track/materials/textures</uri>
          <name>RunningTrack/Ground</name>
        </script></material>
      </visual>
    </link>
  </model>
</sdf>
""")
    print("->", mdir, img.shape, f"{mpp_x * 100:.1f} cm/px")


if __name__ == "__main__":
    main()
